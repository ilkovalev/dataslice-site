// Ссылки на Telegram-канал — по одному месту размещения.
//
// ЗАЧЕМ: track('tg_click') считает КЛИКИ, но не подписки. Сколько людей реально
// пришло из шапки, а сколько из блока в конце урока — по кликам не узнать.
// Telegram считает вступивших по каждой пригласительной ссылке отдельно, и это
// единственный способ увидеть настоящую конверсию.
//
// ЧТО СДЕЛАТЬ ВЛАДЕЛЬЦУ: в Telegram → канал → «Пригласительные ссылки» создать
// четыре ссылки с названиями header / cta / inline / footer и вставить их сюда
// вместо CHANNEL. Пока стоит CHANNEL, всё работает как раньше — просто без
// разбивки по местам. Статистика смотрится там же, в списке ссылок.
const CHANNEL = 'https://t.me/dataslice'

export const TG = {
  header: CHANNEL,
  cta: CHANNEL,
  inline: CHANNEL,
  footer: CHANNEL,
}

// Пост с обратной связью — не про подписку, поэтому вне атрибуции.
export const TG_FEEDBACK = 'https://t.me/dataslice/109'

// Ссылка + место в одном вызове: place попадает и в href, и в аналитику,
// так что разъехаться они не могут.
export const tgLink = (place) => TG[place] ?? CHANNEL
